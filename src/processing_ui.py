def expand_all(window):
    expanded=not all(item.toggle.isChecked() for item in window.step_cards.values())
    for item in window.step_cards.values(): item.toggle.setChecked(expanded)
    window.expand_steps.setText('收起全部' if expanded else '展开全部')
